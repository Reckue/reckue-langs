// Буквенный «прогон» (одна орфографическая часть). Модификаторные апострофы
// орфографий (ʼ U+02BC и пр.) попадают в \p{L} сами; прямой ' и типографский '
// — нет, они работают разделителями и обрабатываются отдельно (APOS/APOS_WORD).
export const WORD_TOKEN = /[\p{L}\p{M}]+/gu;
export const WORD_CHAR = /[\p{L}\p{M}]/u;

// Апостроф как внутрисловный соединитель (для it's / don't / I'm).
export const APOS = /['’]/u;
// Слово с возможным внутренним апострофом — целиком (it's, don't, y'all).
// Раскладка на сегменты и раскрытие сокращений — в [[Contractions]].
export const APOS_WORD = /[\p{L}\p{M}]+(?:['’]+[\p{L}\p{M}]+)*/gu;

/**
 * Value-объект токена: сырьё как на странице + clear-форма (lowercase).
 * Лемматизация вынесена в отдельную стратегию ([[Inflector]]), чтобы её можно
 * было заменить/усилить, не трогая матчинг.
 *
 * Сокращения: вставить отсутствующие буквы (n't→not) поверх Highlight API нельзя —
 * красится только физический участок текста. Но раскрыть сокращение для словаря
 * МОЖНО: физический кусок 's/n't трактуется как полное слово is/not (см.
 * [[Contractions]]), подсвечивается при этом реальный участок 's/n't.
 */
export class Word {

    readonly raw: string;
    readonly clear: string;

    constructor(raw: string) {
        this.raw = raw;
        this.clear = raw.toLowerCase();
    }
}
